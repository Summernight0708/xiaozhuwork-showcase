-- D6 minimal commercial entitlement source of truth.
-- Project-scoped Free / Early Access Pro only. Payment remains out of scope.

create table public.project_entitlements (
  project_id uuid primary key references public.projects(id) on delete cascade,
  plan text not null default 'free',
  status text not null default 'active',
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  granted_at timestamptz not null default now(),
  granted_by uuid references auth.users(id) on delete set null,
  grant_source text not null default 'system_default',
  note text,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_entitlements_plan check (plan in ('free','early_access_pro')),
  constraint project_entitlements_status check (status in ('active','cancelled')),
  constraint project_entitlements_expiry check (expires_at is null or expires_at > starts_at),
  constraint project_entitlements_source_length check (char_length(grant_source) between 1 and 80),
  constraint project_entitlements_note_length check (note is null or char_length(note) <= 2000),
  constraint project_entitlements_version_positive check (version > 0)
);

create table public.project_entitlement_audit (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.projects(id) on delete cascade,
  request_id uuid,
  action text not null,
  plan text not null,
  status text not null,
  starts_at timestamptz not null,
  expires_at timestamptz,
  granted_at timestamptz not null,
  granted_by uuid references auth.users(id) on delete set null,
  grant_source text not null,
  note text,
  entitlement_version integer not null,
  created_at timestamptz not null default now(),
  constraint project_entitlement_audit_action check (action in ('initialized','granted','updated','cancelled')),
  constraint project_entitlement_audit_plan check (plan in ('free','early_access_pro')),
  constraint project_entitlement_audit_status check (status in ('active','cancelled')),
  constraint project_entitlement_audit_version_positive check (entitlement_version > 0)
);
create unique index project_entitlement_audit_request_idx
  on public.project_entitlement_audit(request_id)
  where request_id is not null;
create index project_entitlement_audit_project_idx
  on public.project_entitlement_audit(project_id, created_at desc);

create table private.entitlement_service_commands (
  request_id uuid primary key,
  payload_hash bytea not null,
  result jsonb,
  created_at timestamptz not null default now()
);

alter table public.project_entitlements enable row level security;
alter table public.project_entitlement_audit enable row level security;

revoke all on public.project_entitlements, public.project_entitlement_audit
  from public, anon, authenticated, service_role;
revoke all on private.entitlement_service_commands
  from public, anon, authenticated, service_role;

create function private.initialize_project_entitlement()
returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.project_entitlements(
    project_id, plan, status, starts_at, granted_at, grant_source, version
  ) values (
    new.id, 'free', 'active', coalesce(new.created_at, now()), coalesce(new.created_at, now()), 'system_default', 1
  )
  on conflict (project_id) do nothing;

  insert into public.project_entitlement_audit(
    project_id, action, plan, status, starts_at, expires_at, granted_at,
    granted_by, grant_source, note, entitlement_version
  )
  select e.project_id, 'initialized', e.plan, e.status, e.starts_at, e.expires_at, e.granted_at,
         e.granted_by, e.grant_source, e.note, e.version
  from public.project_entitlements e
  where e.project_id = new.id
    and not exists (
      select 1 from public.project_entitlement_audit a
      where a.project_id = new.id and a.action = 'initialized'
    );

  return new;
end;
$$;

revoke all on function private.initialize_project_entitlement()
  from public, anon, authenticated, service_role;

create trigger projects_initialize_entitlement
after insert on public.projects
for each row execute function private.initialize_project_entitlement();

insert into public.project_entitlements(
  project_id, plan, status, starts_at, granted_at, grant_source, version, created_at, updated_at
)
select p.id, 'free', 'active', p.created_at, p.created_at, 'system_default', 1, p.created_at, p.created_at
from public.projects p
on conflict (project_id) do nothing;

insert into public.project_entitlement_audit(
  project_id, action, plan, status, starts_at, expires_at, granted_at,
  granted_by, grant_source, note, entitlement_version, created_at
)
select e.project_id, 'initialized', e.plan, e.status, e.starts_at, e.expires_at, e.granted_at,
       e.granted_by, e.grant_source, e.note, e.version, e.created_at
from public.project_entitlements e
where not exists (
  select 1 from public.project_entitlement_audit a
  where a.project_id = e.project_id and a.action = 'initialized'
);

create function public.get_project_entitlement(p_project_id uuid)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_actor uuid := auth.uid();
  v_entitlement public.project_entitlements%rowtype;
  v_effective_plan text;
begin
  if v_actor is null then
    return jsonb_build_object('ok',false,'code','UNAUTHENTICATED');
  end if;
  if not private.is_active_member(p_project_id, v_actor) then
    return jsonb_build_object('ok',false,'code','NOT_FOUND_OR_NOT_AUTHORIZED');
  end if;

  select * into v_entitlement
  from public.project_entitlements e
  where e.project_id = p_project_id;

  if not found then
    return jsonb_build_object(
      'ok',true,'projectId',p_project_id,'plan','free','active',true,
      'status','active','startsAt',null,'expiresAt',null,'version',0
    );
  end if;

  v_effective_plan := case
    when v_entitlement.status = 'active'
      and v_entitlement.starts_at <= now()
      and (v_entitlement.expires_at is null or v_entitlement.expires_at > now())
    then v_entitlement.plan
    else 'free'
  end;

  return jsonb_build_object(
    'ok',true,
    'projectId',v_entitlement.project_id,
    'plan',v_effective_plan,
    'active',true,
    'status',case
      when v_entitlement.status='cancelled' then 'cancelled'
      when v_entitlement.plan='early_access_pro' and v_entitlement.starts_at>now() then 'scheduled'
      when v_entitlement.plan='early_access_pro' and v_entitlement.expires_at is not null and v_entitlement.expires_at<=now() then 'expired'
      else v_entitlement.status
    end,
    'startsAt',v_entitlement.starts_at,
    'expiresAt',v_entitlement.expires_at,
    'version',v_entitlement.version
  );
end;
$$;

revoke all on function public.get_project_entitlement(uuid)
  from public, anon, authenticated, service_role;
grant execute on function public.get_project_entitlement(uuid) to authenticated;

create function public.cmd_set_project_entitlement_service(
  p_project_id uuid,
  p_request_id uuid,
  p_plan text,
  p_status text,
  p_starts_at timestamptz,
  p_expires_at timestamptz,
  p_granted_by uuid,
  p_grant_source text,
  p_note text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_hash bytea;
  v_existing_cmd private.entitlement_service_commands%rowtype;
  v_before public.project_entitlements%rowtype;
  v_after public.project_entitlements%rowtype;
  v_action text;
  v_result jsonb;
begin
  if p_request_id is null then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','requestId');
  end if;
  if not exists(select 1 from public.projects p where p.id = p_project_id) then
    return jsonb_build_object('ok',false,'code','NOT_FOUND_OR_NOT_AUTHORIZED','requestId',p_request_id);
  end if;
  if p_plan not in ('free','early_access_pro') then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','plan','requestId',p_request_id);
  end if;
  if p_status not in ('active','cancelled') then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','status','requestId',p_request_id);
  end if;
  if p_starts_at is null then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','startsAt','requestId',p_request_id);
  end if;
  if p_expires_at is not null and p_expires_at <= p_starts_at then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','expiresAt','requestId',p_request_id);
  end if;
  if p_grant_source is null or char_length(btrim(p_grant_source)) not between 1 and 80 then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','grantSource','requestId',p_request_id);
  end if;
  if p_note is not null and char_length(p_note) > 2000 then
    return jsonb_build_object('ok',false,'code','VALIDATION_FAILED','field','note','requestId',p_request_id);
  end if;

  v_hash := private.payload_hash(jsonb_build_object(
    'projectId',p_project_id,'plan',p_plan,'status',p_status,
    'startsAt',p_starts_at,'expiresAt',p_expires_at,'grantedBy',p_granted_by,
    'grantSource',btrim(p_grant_source),'note',p_note
  ));

  insert into private.entitlement_service_commands(request_id,payload_hash,result)
  values(p_request_id,v_hash,null)
  on conflict (request_id) do nothing;

  select * into v_existing_cmd
  from private.entitlement_service_commands c
  where c.request_id = p_request_id
  for update;

  if v_existing_cmd.payload_hash <> v_hash then
    return jsonb_build_object('ok',false,'code','IDEMPOTENCY_KEY_REUSED','requestId',p_request_id,'replayed',false);
  end if;
  if v_existing_cmd.result is not null then
    return jsonb_set(v_existing_cmd.result,'{replayed}','true'::jsonb,true);
  end if;

  select * into v_before
  from public.project_entitlements e
  where e.project_id = p_project_id
  for update;

  if not found then
    raise exception 'project entitlement missing for project %', p_project_id;
  end if;

  update public.project_entitlements
  set plan = p_plan,
      status = p_status,
      starts_at = p_starts_at,
      expires_at = p_expires_at,
      granted_at = now(),
      granted_by = p_granted_by,
      grant_source = btrim(p_grant_source),
      note = p_note,
      version = version + 1,
      updated_at = now()
  where project_id = p_project_id
  returning * into v_after;

  v_action := case
    when p_status = 'cancelled' then 'cancelled'
    when v_before.plan = 'free' and p_plan = 'early_access_pro' then 'granted'
    else 'updated'
  end;

  insert into public.project_entitlement_audit(
    project_id, request_id, action, plan, status, starts_at, expires_at,
    granted_at, granted_by, grant_source, note, entitlement_version
  ) values (
    v_after.project_id, p_request_id, v_action, v_after.plan, v_after.status,
    v_after.starts_at, v_after.expires_at, v_after.granted_at, v_after.granted_by,
    v_after.grant_source, v_after.note, v_after.version
  );

  v_result := jsonb_build_object(
    'ok',true,
    'data',jsonb_build_object(
      'projectId',v_after.project_id,'plan',v_after.plan,'status',v_after.status,
      'startsAt',v_after.starts_at,'expiresAt',v_after.expires_at,'version',v_after.version
    ),
    'requestId',p_request_id,'replayed',false
  );

  update private.entitlement_service_commands
  set result = v_result
  where request_id = p_request_id;

  return v_result;
end;
$$;

revoke all on function public.cmd_set_project_entitlement_service(
  uuid,uuid,text,text,timestamptz,timestamptz,uuid,text,text
) from public, anon, authenticated, service_role;
grant execute on function public.cmd_set_project_entitlement_service(
  uuid,uuid,text,text,timestamptz,timestamptz,uuid,text,text
) to service_role;
