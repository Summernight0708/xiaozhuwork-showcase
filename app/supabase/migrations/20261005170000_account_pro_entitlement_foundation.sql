create or replace function private.project_has_active_account_pro_source(
  p_project_id uuid,
  p_at timestamptz
) returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.project_members pm
    where pm.project_id = p_project_id
      and pm.member_state = 'active'
      and pm.user_id is not null
      and pm.role in ('leader','admin','member')
      and private.is_account_pro(pm.user_id, p_at)
  );
$$;

create or replace function private.project_last_account_pro_source_end(
  p_project_id uuid,
  p_at timestamptz
) returns timestamptz
language sql
stable
security definer
set search_path = ''
as $$
  select max(e.expires_at)
  from public.project_members pm
  join public.account_entitlements e on e.user_id = pm.user_id
  where pm.project_id = p_project_id
    and pm.member_state = 'active'
    and pm.user_id is not null
    and pm.role in ('leader','admin','member')
    and e.plan = 'pro'
    and e.status = 'active'
    and e.starts_at <= p_at
    and e.expires_at <= p_at;
$$;

