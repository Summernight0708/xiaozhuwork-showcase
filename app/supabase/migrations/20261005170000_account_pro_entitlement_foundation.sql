create or replace function private.is_account_pro(
  p_user_id uuid,
  p_at timestamptz
) returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.account_entitlements e
    where e.user_id = p_user_id
      and e.plan = 'pro'
      and e.status = 'active'
      and e.starts_at <= p_at
      and p_at < e.expires_at
  );
$$;

create or replace function private.account_entitlement_state(
  p_user_id uuid,
  p_at timestamptz
) returns table(
  plan text,
  state text,
  starts_at timestamptz,
  expires_at timestamptz,
  version integer
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_row public.account_entitlements%rowtype;
begin
  select *
  into v_row
  from public.account_entitlements e
  where e.user_id = p_user_id;

  if not found then
    return query select 'free'::text, 'free'::text, null::timestamptz, null::timestamptz, 0;
    return;
  end if;

  if v_row.status = 'cancelled' then
    return query
      select 'free'::text, 'cancelled'::text, v_row.starts_at, v_row.expires_at, v_row.version;
  elsif p_at < v_row.starts_at then
    return query
      select 'free'::text, 'scheduled'::text, v_row.starts_at, v_row.expires_at, v_row.version;
  elsif p_at >= v_row.expires_at then
    return query
      select 'free'::text, 'expired'::text, v_row.starts_at, v_row.expires_at, v_row.version;
  else
    return query
      select 'pro'::text, 'active'::text, v_row.starts_at, v_row.expires_at, v_row.version;
  end if;
end;
$$;

