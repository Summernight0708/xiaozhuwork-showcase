create or replace function private.account_active_free_project_count(
  p_user_id uuid,
  p_at timestamptz
) returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(distinct pm.project_id)::integer
  from public.project_members pm
  join public.projects p on p.id = pm.project_id
  where pm.user_id = p_user_id
    and pm.member_state = 'active'
    and p.archived_at is null
    and exists (
      select 1
      from private.resolve_project_entitlement(pm.project_id,p_at) e
      where e.state = 'free'
    );
$$;

