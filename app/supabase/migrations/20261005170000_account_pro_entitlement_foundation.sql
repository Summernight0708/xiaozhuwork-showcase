  constraint account_entitlement_audit_plan check (plan = 'pro'),
  constraint account_entitlement_audit_status check (status in ('active','cancelled')),
  constraint account_entitlement_audit_expiry check (expires_at > starts_at),
  constraint account_entitlement_audit_version_positive check (entitlement_version > 0)
