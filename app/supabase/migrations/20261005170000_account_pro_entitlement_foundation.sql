create or replace function private.resolve_project_entitlement(
  p_project_id uuid,
  p_at timestamptz
) returns table(
  plan text,
  state text,
  source text,
  grace_expires_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_persisted_grace timestamptz;
  v_last_source_end timestamptz;
  v_dynamic_grace timestamptz;
  v_grace_end timestamptz;
begin
  if private.project_has_active_account_pro_source(p_project_id, p_at) then
    return query select 'pro'::text, 'active'::text, 'account_member'::text, null::timestamptz;
    return;
  end if;

  if private.has_project_level_pro_grant(p_project_id, p_at) then
    return query select 'pro'::text, 'active'::text, 'project_grant'::text, null::timestamptz;
    return;
  end if;

  select g.expires_at
  into v_persisted_grace
  from public.project_pro_grace g
  where g.project_id = p_project_id
    and g.expires_at > p_at;

  v_last_source_end := private.project_last_account_pro_source_end(p_project_id, p_at);
  if v_last_source_end is not null
     and v_last_source_end + interval '3 days' > p_at then
    v_dynamic_grace := v_last_source_end + interval '3 days';
  end if;

  if v_persisted_grace is null then
    v_grace_end := v_dynamic_grace;
  elsif v_dynamic_grace is null then
    v_grace_end := v_persisted_grace;
  else
    v_grace_end := greatest(v_persisted_grace, v_dynamic_grace);
  end if;

  if v_grace_end is not null and v_grace_end > p_at then
    return query select 'pro'::text, 'grace'::text, 'grace'::text, v_grace_end;
    return;
  end if;

  return query select 'free'::text, 'free'::text, 'none'::text, null::timestamptz;
end;
$$;

create or replace function public.get_project_entitlement(p_project_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_entitlement record;
begin
  if v_actor is null then
    return jsonb_build_object('ok',false,'code','UNAUTHENTICATED');
  end if;
  if not private.is_active_member(p_project_id, v_actor) then
    return jsonb_build_object('ok',false,'code','NOT_FOUND_OR_NOT_AUTHORIZED');
  end if;

  select *
  into v_entitlement
  from private.resolve_project_entitlement(p_project_id, transaction_timestamp());

  return jsonb_build_object(
    'ok', true,
    'projectId', p_project_id,
    'plan', v_entitlement.plan,
    'state', v_entitlement.state,
    'source', v_entitlement.source,
    'graceExpiresAt', v_entitlement.grace_expires_at
  );
end;
$$;

