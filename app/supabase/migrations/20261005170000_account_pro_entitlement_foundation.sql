create or replace function private.project_has_capability(
  p_project_id uuid,
  p_capability text
) returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_entitlement record;
begin
  if p_capability not in (
    'file_full_history',
    'file_batch_rollback',
    'file_version_compare',
    'project_recovery_point',
    'enhanced_report',
    'advanced_permissions',
    'project_statistics',
    'external_integrations'
  ) then
    return false;
  end if;

  select *
  into v_entitlement
  from private.resolve_project_entitlement(p_project_id, transaction_timestamp());

  if v_entitlement.state not in ('active','grace') then
    return false;
  end if;

  -- P0 deliberately ships no released Pro capability. P3 registers only
  -- capabilities whose implementation commit has been integrated and verified.
  return false;
end;
$$;

