-- P0 account-level Pro entitlement foundation.
-- Forward-only migration from legacy project-scoped Early Access entitlements.
-- Payment, P1 quota enforcement, P2 commercial UI, and P3 capability release remain out of scope.

create or replace function private.assert_no_legacy_project_pro()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1
    from public.project_entitlements e
    where e.plan = 'early_access_pro'
  ) then
    raise exception using
      errcode = 'P0001',
      message = 'LEGACY_PROJECT_PRO_FOUND';
  end if;
end;
$$;

revoke all on function private.assert_no_legacy_project_pro()
  from public, anon, authenticated, service_role;

select private.assert_no_legacy_project_pro();

create table public.account_entitlements (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan text not null,
  status text not null,
  starts_at timestamptz not null,
  expires_at timestamptz not null,
  granted_at timestamptz not null default now(),
  granted_by uuid references auth.users(id) on delete set null,
  grant_source text not null,
  note text,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint account_entitlements_plan check (plan = 'pro'),
  constraint account_entitlements_status check (status in ('active','cancelled')),
  constraint account_entitlements_expiry check (expires_at > starts_at),
  constraint account_entitlements_source_length check (char_length(grant_source) between 1 and 80),
  constraint account_entitlements_note_length check (note is null or char_length(note) <= 2000),
  constraint account_entitlements_version_positive check (version > 0)
);

